pub fn names_for(lcid: Option<u32>) -> &'static DateNames {
    let Some(id) = lcid else { return &EN_NZ };
    match id & 0xFFFF {
        0x1409 | 0x1809 | 0x1C09 | 0x2009 | 0x4809 => &EN_NZ,
        0x0009 | 0x0409 | 0x0809 | 0x0C09 | 0x1009 | 0x4009 | 0x4409 => &EN,
        0x0007 | 0x0407 | 0x1007 | 0x1407 => &DE,
        0x0807 => &DE_CH,
        0x000C | 0x040C | 0x080C | 0x0C0C | 0x100C | 0x140C | 0x180C => &FR,
        0x000A | 0x040A | 0x0C0A => &ES,
        0x080A => &ES_MX,
        0x0010 | 0x0410 | 0x0810 => &IT,
        0x0016 | 0x0416 | 0x0816 => &PT,
        0x0013 | 0x0413 | 0x0813 => &NL,
        0x0019 | 0x0419 => &RU,
        0x0011 | 0x0411 => &JA,
        0x0804 => &ZH,
        0x0401 => &LC_0401,
        0x0404 => &LC_0404,
        0x0405 => &LC_0405,
        0x0406 => &LC_0406,
        0x0408 => &LC_0408,
        0x040B => &LC_040B,
        0x040D => &LC_040D,
        0x040E => &LC_040E,
        0x0412 => &LC_0412,
        0x0414 => &LC_0414,
        0x0415 => &LC_0415,
        0x0418 => &LC_0418,
        0x041D => &LC_041D,
        0x041E => &LC_041E,
        0x041F => &LC_041F,
        0x0421 => &LC_0421,
        0x0422 => &LC_0422,
        0x042A => &LC_042A,
        0x0439 => &LC_0439,
        0x0C07 => &LC_0C07,
        0x2C0A => &LC_2C0A,
        _ => &EN_NZ,
    }
}

