use crate::locale::{DAY_NAMES, MONTH_NAMES};

pub struct DateNames {
    pub months: [&'static str; 12],
    pub months_abbr: [&'static str; 12],
    pub days: [&'static str; 7],
    pub days_abbr: [&'static str; 7],
    pub am: &'static str,
    pub pm: &'static str,
}

impl DateNames {
    pub fn month_initial(&self, m: usize) -> &'static str {
        let s = self.months[m];
        s.char_indices().nth(1).map_or(s, |(i, _)| &s[..i])
    }
}

