struct Table {
    start: Vec<u32>,
    year: Vec<u16>,
    month: Vec<u8>,
    splits: Vec<u32>,
}

fn bit(s: &[u8], i: usize) -> bool {
    let d = (s[i / 4] as char).to_digit(16).unwrap_or(0);
    (d >> (i % 4)) & 1 == 1
}

fn table() -> &'static Table {
    static T: OnceLock<Table> = OnceLock::new();
    T.get_or_init(|| {
        let (lens, lo, hi) = (LENGTHS.as_bytes(), STEP_LO.as_bytes(), STEP_HI.as_bytes());
        let n = lens.len() * 4;
        let mut exc = std::collections::HashMap::new();
        let mut at = 0usize;
        for e in EXCEPTIONS.split(',') {
            let (d, l) = e.split_once(':').unwrap_or(("0", "30"));
            at += d.parse::<usize>().unwrap_or(0);
            exc.insert(at, l.parse::<u32>().unwrap_or(30));
        }
        let mut t = Table {
            start: Vec::with_capacity(n),
            year: Vec::with_capacity(n),
            month: Vec::with_capacity(n),
            splits: Vec::new(),
        };
        let mut at = 0u32;
        for d in SPLITS.split(',') {
            at += d.parse::<u32>().unwrap_or(0);
            t.splits.push(at);
        }
        let (mut s, mut y, mut m) = (17u32, 1899u16, 13u8);
        for i in 0..n {
            if i > 0 {
                match (bit(hi, i), bit(lo, i)) {
                    (false, false) => m += 1,
                    (false, true) => (y, m) = (y + 1, 1),
                    (true, false) => (y, m) = (y + 1, 13),
                    (true, true) => m = 1,
                }
            }
            t.start.push(s);
            t.year.push(y);
            t.month.push(m);
            s += exc
                .get(&i)
                .copied()
                .unwrap_or(if bit(lens, i) { 30 } else { 29 });
        }
        t
    })
}

pub fn from_serial(serial: i64) -> (i64, u32, u32) {
    if serial < 17 {
        return (1899, 12, (serial + 14) as u32);
    }
    let t = table();
    let i = t.start.partition_point(|&s| i64::from(s) <= serial) - 1;

    let from = t
        .splits
        .partition_point(|&p| i64::from(p) <= i64::from(t.start[i]));
    let long = t.start.get(i + 1).is_some_and(|&n| n - t.start[i] == 31);
    let bumped = t.splits.get(from).is_some_and(|&p| i64::from(p) <= serial);
    (
        i64::from(t.year[i]) + i64::from(bumped),
        u32::from(t.month[i]),
        (serial - i64::from(t.start[i]) + 1 - i64::from(bumped && long)) as u32,
    )
}

