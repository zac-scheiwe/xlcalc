fn bit(s: &[u8], i: usize) -> bool {
    let d = (s[i / 4] as char).to_digit(16).unwrap_or(0);
    (d >> (i % 4)) & 1 == 1
}

fn indices(s: &str) -> std::collections::HashSet<usize> {
    let mut at = 0usize;
    s.split(',')
        .filter(|d| !d.is_empty())
        .map(|d| {
            at += d.parse::<usize>().unwrap_or(0);
            at
        })
        .collect()
}

