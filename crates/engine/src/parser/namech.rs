fn in_table(t: &[(u16, u16)], u: u16) -> bool {
    t.binary_search_by(|&(a, b)| {
        if u < a {
            std::cmp::Ordering::Greater
        } else if u > b {
            std::cmp::Ordering::Less
        } else {
            std::cmp::Ordering::Equal
        }
    })
    .is_ok()
}

pub fn name_char(c: char, first: bool) -> bool {
    match u16::try_from(c as u32) {
        Ok(u) => in_table(if first { &FIRST } else { &REST }, u),
        Err(_) => true,
    }
}
