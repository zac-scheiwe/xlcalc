pub(crate) fn class_at(name: &str, classes: &str, i: usize) -> u8 {
    let b = classes.as_bytes();
    if i < b.len() {
        return b[i];
    }
    match name {
        "SUMIFS" | "AVERAGEIFS" | "MAXIFS" | "MINIFS" | "SORTBY" => {
            if i.is_multiple_of(2) {
                b'V'
            } else {
                b[1]
            }
        }
        "COUNTIFS" => {
            if i.is_multiple_of(2) {
                b'Q'
            } else {
                b'V'
            }
        }
        _ => b[b.len() - 1],
    }
}

