from decimal import Decimal as D, getcontext
from fractions import Fraction as F
import struct

getcontext().prec = 100

def trunc(q, keep):
    q = F(q)
    if q == 0:
        return 0.0
    e = q.numerator.bit_length() - q.denominator.bit_length()
    if F(2) ** e > q:
        e -= 1
    s = F(2) ** (keep - 1 - e)
    return float(F(int(q * s)) / s)

def bits(x):
    return struct.unpack("<Q", struct.pack("<d", x))[0]

def pi_scaled(prec):
    def atan_inv(n):
        t, s, k, sign = (1 << (prec + 32)) // n, 0, 1, 1
        while t:
            s += sign * (t // k)
            t //= n * n
            k += 2
            sign = -sign
        return s
    return (4 * (4 * atan_inv(5) - atan_inv(239))) >> 32

def table(name, doc, vals, ty="u64"):
    out = [f"/// {line}" for line in doc.split("\n")]
    out.append(f"pub(super) const {name}: [{ty}; {len(vals)}] = [")
    out += [f"    {v}," for v in vals]
    out.append("];")
    return "\n".join(out) + "\n"

def hexes(xs):
    return [f"{bits(x):#018x}" for x in xs]

parts = ["//! Generated by gen_tables.py (see there for how each table is derived). Do not edit.\n"]

two = [D(2) ** (D(j) / 64) for j in range(64)]
lead = [trunc(t, 25) for t in two]
parts.append(table("EXP_FULL", "2^(j/64) rounded to nearest (exp).", hexes(float(F(t)) for t in two)))
parts.append(table("EXP_LEAD", "2^(j/64) truncated to 25 significant bits (exp and pow).", hexes(lead)))
parts.append(table("EXP_TAIL", "2^(j/64) - EXP_LEAD[j], truncated to 53 bits (exp and pow).",
                   hexes(trunc(F(t) - F(l), 53) for t, l in zip(two, lead))))

ln = [(1 + D(j) / 256).ln() for j in range(257)]
lead = [trunc(v, 25) for v in ln]
lead[256] = trunc(D(2).ln(), 24)
parts.append(table("LOG_LEAD", "ln(1 + j/256) truncated to 25 significant bits (the last, ln 2, to 24).",
                   hexes(lead)))
parts.append(table("LOG_TAIL", "ln(1 + j/256) - LOG_LEAD[j], truncated to 53 bits.",
                   hexes(trunc(F(v) - F(l), 53) for v, l in zip(ln, lead))))
inv = [F(2) / (1 + F(j, 256)) for j in range(257)]
parts.append(table("LOG_INV", "2/(1 + j/256) rounded to nearest (log).", hexes(float(v) for v in inv)))
invh = [trunc(v, 9) for v in inv]
parts.append(table("POW_INV_HEAD", "2/(1 + j/256) truncated to 9 significant bits (pow).", hexes(invh)))
parts.append(table("POW_INV_TAIL", "2/(1 + j/256) - POW_INV_HEAD[j], rounded to nearest (pow).",
                   hexes(float(v - F(h)) for v, h in zip(inv, invh))))

n = 1220
x = (1 << (n + 1300)) // (2 * pi_scaled(1300))
s = bin(x)[2:].zfill(n)
groups = [0] * 6 + [int(s[i:i + 10], 2) for i in range(0, 1200, 10)] + [0]
parts.append(table("PIBITS", "The bits of 1/(2 pi), 10 to an entry, after 60 zero bits (__remainder_piby2).",
                   [str(g) for g in groups]))
print("\n".join(parts), end="")
