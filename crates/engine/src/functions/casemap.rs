const TURKIC: u8 = 1;

fn run(runs: &[(u16, u16, u16)], u: u16) -> Option<(u16, u16, u16)> {
    let r = *runs.iter().find(|r| u <= r.1)?;
    (u >= r.0).then_some(r)
}

pub(crate) fn upper_plain(u: u16, culture: u8) -> u16 {
    let Some((_, _, c)) = run(UPPER_RUNS, u) else {
        return u;
    };
    let d = u.wrapping_sub(c);
    if (c as i16) > 255 {
        UPPER_BIG[d as usize]
    } else if c <= 1 {
        (d & 0xFFFE).wrapping_add(c)
    } else if d == 0x49 && culture == TURKIC {
        0x130
    } else {
        d
    }
}

pub(crate) fn upper_unit(u: u16) -> u16 {
    if !(0x384..=0x3CE).contains(&u) {
        return upper_plain(u, 0);
    }
    let e = if (0xC0..=0x17F).contains(&u) {
        GREEK_FOLD[(u - 0xC0) as usize]
    } else if u & 0xFF98 == 0x388 {
        GREEK_TONOS[(((u >> 2) & 0x18) | (u & 7)) as usize]
    } else if u == 0x386 {
        0x391
    } else {
        u
    };
    let r = upper_plain(e, 2);
    if e == r {
        u
    } else {
        r
    }
}

pub(crate) fn lower_plain(u: u16, culture: u8) -> u16 {
    let Some((_, _, c)) = run(LOWER_RUNS, u) else {
        return u;
    };
    let r = u.wrapping_add(c);
    if (c as i16) >= 0 {
        if r == 0x69 && culture == TURKIC {
            0x131
        } else {
            r
        }
    } else {
        LOWER_BIG[r as usize]
    }
}
