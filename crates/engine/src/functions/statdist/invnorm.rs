fn std_normal_tail(q: f64) -> f64 {
    let r = x87::sqrt(-x87::ln(q));
    let (num, den, s) = if r <= 5.0 {
        (&TAIL_NUM_A, &TAIL_DEN_A, x87::sub(r, 1.6))
    } else {
        (&TAIL_NUM_B, &TAIL_DEN_B, x87::sub(r, 5.0))
    };
    let d = horner(den, s);
    x87::div(horner(num, s), d)
}

pub fn inverse_erf(y: f64) -> f64 {
    let y2 = x87::mul(y, y);
    if y <= std::f64::consts::FRAC_1_SQRT_2 {
        let d = horner(&DEN_0, y2);
        return x87::mul(y, x87::div(horner(&NUM_0, y2), d));
    }
    if y <= 0.9375 {
        let w = x87::sqrt(-x87::ln(x87::add(-y, 1.0)));
        let r = if y <= 0.85 {
            let d = horner(&DEN_1, y2);
            x87::div(horner(&NUM_1, y2), d)
        } else {
            let z = x87::sub(y, 0.87890625);
            let d = horner(&DEN_2, z);
            x87::div(horner(&NUM_2, z), d)
        };
        return x87::mul(w, r);
    }

    let q = x87::mul(x87::sub(1.0, y), 0.5);
    x87::mul(std_normal_tail(q), std::f64::consts::FRAC_1_SQRT_2)
}

pub fn norm_s_inv(p: f64) -> f64 {
    if (0.075..=0.9375).contains(&p) {
        let y = x87::sub(x87::mul(p, 2.0), 1.0);
        let t = inverse_erf(y.abs());
        let t = if y < 0.0 { -t } else { t };
        return x87::mul(t, std::f64::consts::SQRT_2);
    }
    if p < 0.5 {
        -std_normal_tail(p)
    } else {
        std_normal_tail(x87::sub(1.0, p))
    }
}
