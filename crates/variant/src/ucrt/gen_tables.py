from decimal import Decimal as D, getcontext
from fractions import Fraction as F
import struct

getcontext().prec = 100

def bits(x):
    return struct.unpack("<Q", struct.pack("<d", x))[0]

def double(b):
    return struct.unpack("<d", struct.pack("<Q", b))[0]

out = ["//! Generated by gen_tables.py (see there for how each table is derived). Do not edit.\n"]

OFF = 0x3FE6955500000000
N = 128
rows = []
for i in range(N):
    lo, hi = double(OFF + (i << 45)), double(OFF + ((i + 1) << 45))
    centre = (F(lo) + F(hi)) / 2
    invc = F(round(N / centre), N) if centre < 1 else F(round(2 * N / centre), 2 * N)
    log_c = (D(invc.denominator) / D(invc.numerator)).ln()
    logc = float(F(round(D(2) ** 43 * log_c), 2**43))
    tail = float(log_c - D(logc))
    rows.append(f"    [{bits(float(invc)):#018x}, {bits(logc):#018x}, {bits(tail):#018x}],")
out.append("/// 1/c, log(c) to 2^-43 and the rest of log(c), for the 128 subintervals of log's z.")
out.append(f"pub(super) const LOG: [[u64; 3]; {N}] = [")
out += rows
out.append("];\n")

N = 256
vals = []
for k in range(N):
    t = D(2) ** (D(k) / N)
    h = float(t)
    vals.append(f"    {bits(float((t - D(h)) / D(h))):#018x},")
    vals.append(f"    {(bits(h) - (k << 52) // N) % 2**64:#018x},")
out.append("/// T[k] and H[k]'s bits less (k << 52)/256, k = 0..255: 2^(k/256) = H[k] (1 + T[k]).")
out.append(f"pub(super) const EXP: [u64; {2 * N}] = [")
out += vals
out.append("];")
print("\n".join(out))
